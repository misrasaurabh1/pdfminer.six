fn glyph_map() -> &'static HashMap<&'static str, u32> {
    GLYPH_MAP.get_or_init(build_glyph_map)
}

/// Look up Unicode codepoint for an Adobe glyph name.
/// Returns None if the glyph name is not found.
#[pyfunction]
pub fn glyph_name_to_unicode(name: &str) -> Option<u32> {
    glyph_map().get(name).copied()
}

/// Look up character width from a flat CID->width dict (as list of (cid, width) pairs).
/// Returns default_width if the CID is not found.
///
/// The widths are passed as a list of (cid: int, width: float) tuples,
/// mirroring the PDFFont.widths dict but as a sorted vec for fast lookup.
#[pyfunction]
pub fn lookup_char_width(
    widths: Vec<(u64, f64)>,
    default_width: f64,
    cid: u64,
) -> f64 {
    for (c, w) in &widths {
        if *c == cid {
            return *w;
        }
    }
    default_width
}

/// Batch decode bytes using an encoding table.
/// encoding is a list of Option<String> where encoding[cid] is the glyph name or None.
/// Returns a list of CIDs (each byte value is used as a CID directly).
#[pyfunction]
pub fn decode_with_encoding(
    _encoding: Vec<Option<String>>,
    data: &[u8],
) -> PyResult<Vec<u32>> {
    Ok(data.iter().map(|&b| b as u32).collect())
}

pub fn register(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_function(wrap_pyfunction!(glyph_name_to_unicode, m)?)?;
    m.add_function(wrap_pyfunction!(lookup_char_width, m)?)?;
    m.add_function(wrap_pyfunction!(decode_with_encoding, m)?)?;
    Ok(())
}
